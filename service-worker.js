// Service Worker для Mr. Mouse — делает сайт по-настоящему надёжным офлайн
// ПОСЛЕ первого успешного захода (актуально для тех, кто добавил сайт на
// «Экран Домой»). Работает только для страницы, открытой как обычный сайт
// (https://...) — на скачанный локальный файл (offline.html) это никак не
// влияет, там Service Worker вообще не регистрируется браузером.
//
// Стратегия — "сеть в приоритете" (вы выбрали именно этот вариант):
// пока есть интернет, всегда отдаём самую свежую версию с сервера и тут же
// обновляем кэш; как только сети нет — отдаём то, что успело закэшироваться
// при последнем успешном заходе, вместо пустого экрана с ошибкой.
//
// 08.09.2026: раньше "сеть в приоритете" означало БЕЗ ограничения по
// времени — respondWith ждал fetch(req) сколько угодно. На слабой
// мобильной сети (плохой Wi-Fi/сотовая связь в магазине) это выглядело
// как "зависшая" кнопка/переход: человек нажимал "Открыть каталог" (или
// просто открывал сайт), а страница подолгу не отвечала, потому что
// Service Worker всё это время молча ждал сетевой ответ, вместо того
// чтобы сразу показать то, что уже есть в кэше. Теперь сеть и кэш
// "бегут наперегонки" с ограничением NETWORK_TIMEOUT_MS: если сеть не
// успела вовремя — тут же отдаём кэш, а сетевой ответ (когда всё же
// придёт) всё равно обновит кэш в фоне для следующего захода. Когда сеть
// быстрая (обычный случай) — поведение не меняется, отдаём именно её.
const NETWORK_TIMEOUT_MS = 3000;

// status-2026-09-24: две связанные правки — см. подробные комментарии в
// самом обработчике fetch ниже.
// 1) Ключ, под которым ответ хранится/ищется в кэше, теперь БЕЗ query-
//    строки — раньше catalog.json (у него query — метка времени, меняется
//    на каждый запрос) почти никогда не находился в кэше офлайн, потому
//    что каждый раз искался под новым ключом.
// 2) Запасной "отдать index.html" срабатывает только для самой страницы
//    (навигации), а не для любого не найденного в кэше ресурса — раньше
//    он мог по ошибке подменить, например, несовпавший по версии photos.js
//    содержимым index.html.
// Смена схемы кэширования — повод поднять версию, чтобы старые записи
// (сохранённые под прежними, "грязными" ключами с query-строкой) не
// копились в хранилище бесполезным мусором, а просто разом заменились
// новыми при следующей активации.
const CACHE_VERSION = 'mrmouse-v10';
const APP_SHELL = [
  './',
  'index.html',
  'pc.html',
  'manager.html',
  'photos.js',
  'manifest.json',
  'manifest-manager.json',
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_VERSION).then((cache) => {
      // Кэшируем по одному — если какой-то один ресурс временно недоступен
      // (например, ещё не закоммитился photos.js), это не должно срывать
      // установку всего Service Worker целиком
      return Promise.all(
        APP_SHELL.map((url) =>
          cache.add(url).catch((err) => {
            console.warn('[SW] не удалось закэшировать', url, err);
          })
        )
      );
    })
  );
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(
        keys.filter((k) => k !== CACHE_VERSION).map((k) => caches.delete(k))
      )
    )
  );
  self.clients.claim();
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  // Трогаем только свои GET-запросы — сторонние ресурсы (шрифты, Telegram
  // SDK, сама NocoDB) не кэшируем, у них своя логика и свои CORS-правила
  if (req.method !== 'GET') return;
  // status-2026-09-30: запросы "кусками" (заголовок Range) — так Safari/iPhone
  // грузит ВИДЕО (мышонок на экране бездействия, idle_loop_mouse.mp4) — не
  // трогаем, пусть браузер обрабатывает сам. Иначе при медленной сети наш
  // запасной ответ из кэша (целый файл вместо запрошенного куска) Safari
  // отвергает, и видео не запускается; а кэшировать такие частичные ответы
  // (206) Cache Storage всё равно не умеет.
  if (req.headers.has('range')) return;
  // status-2026-09-30 (f): живая сверка наличия/цен перед заказом (заголовок
  // X-Live) — только свежие данные из сети, без подмены старой копией из кэша
  // при медленной сети (иначе проверка "успешно" сверилась бы со старьём).
  if (req.headers.get('x-live') === '1') return;
  let url;
  try {
    url = new URL(req.url);
  } catch (e) {
    return;
  }
  if (url.origin !== self.location.origin) return;

  // Ключ для ЧТЕНИЯ/ЗАПИСИ в собственном кэше — без query-строки. У части
  // наших же запросов query — это намеренный cache-buster (?t=<время> у
  // catalog.json, он меняется буквально на каждый заход; ?v=<хэш> у
  // photos.js/banners.js — при каждом деплое с новым содержимым), нужный
  // только чтобы обойти HTTP-кэш браузера/CDN. Если хранить/искать записи
  // в Cache Storage под ПОЛНЫМ URL вместе с этой строкой (как было раньше),
  // caches.match() почти никогда не находит совпадение офлайн — прошлая
  // успешная копия лежит под ДРУГИМ значением ?t=/?v=, чем то, что
  // запрашивается сейчас. Сам сетевой запрос (fetch(req) ниже) всё равно
  // уходит с оригинальной query-строкой не тронутым — cache-buster
  // по-прежнему работает против HTTP-кэша при обращении к сети — а вот
  // результат сохраняется и разыскивается уже под одним и тем же "чистым"
  // адресом, поэтому последняя успешно скачанная версия находится всегда.
  const cacheKey = url.origin + url.pathname;

  event.respondWith(
    (async () => {
      // Сетевой запрос запускаем один раз и переиспользуем и в гонке с
      // таймаутом, и (если понадобится) как "последнюю надежду" ниже —
      // fetch() нельзя вызывать повторно для одного и того же объекта Request.
      const networkPromise = fetch(req)
        .then((networkResponse) => {
          // Сеть ответила — тут же обновляем кэш этой свежей версией,
          // чтобы следующий офлайн-заход (или следующий тайм-аут) получил
          // именно её
          const copy = networkResponse.clone();
          caches.open(CACHE_VERSION).then((cache) => cache.put(cacheKey, copy));
          return networkResponse;
        })
        .catch(() => null);

      const timedOut = Symbol('timeout');
      const timeoutPromise = new Promise((resolve) => {
        setTimeout(() => resolve(timedOut), NETWORK_TIMEOUT_MS);
      });

      const first = await Promise.race([networkPromise, timeoutPromise]);
      if (first && first !== timedOut) return first; // сеть успела вовремя

      // Сеть не ответила за отведённое время (или недоступна совсем) —
      // не заставляем человека ждать дальше, отдаём то, что уже лежит в
      // кэше с прошлого раза. Запасной вариант "отдать закэшированный
      // index.html" — ТОЛЬКО для навигационных запросов (открытие самой
      // страницы, req.mode === 'navigate'): именно там пустой экран хуже,
      // чем показать главную страницу из кэша. Для любого другого ресурса
      // (скрипт, JSON, картинка), которого нет в кэше под своим ключом,
      // подменять его содержимым index.html нельзя — это не то же самое и
      // либо не распарсится вовсе, либо приведёт совсем не к тому, что
      // ожидал вызывающий код; честнее в этом случае просто уйти дальше —
      // на "донадеемся на сеть" ниже.
      const cached = (await caches.match(cacheKey))
        || (req.mode === 'navigate' ? await caches.match('index.html') : null);
      if (cached) return cached;

      // В кэше тоже ничего нет (например, самый первый заход и он же
      // оказался медленным) — донадеемся на сеть до конца, это лучше,
      // чем сразу показать ошибку
      const late = await networkPromise;
      return late || Response.error();
    })()
  );
});
